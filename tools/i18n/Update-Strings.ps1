# Regenerates src/ProGuard.UI/Resources/Strings.cs from Strings.resx: one property per string, so code uses Strings.Key
# and XAML uses {x:Static r:Strings.Key}, and a key that doesn't exist fails the build.
# Run it after adding, renaming or removing a key in Strings.resx. A test (StringsResourceTests) fails while they differ.
#
# Why not the SDK's StronglyTypedFileName generation: WPF compiles XAML in a first pass (the *_wpftmp project) that
# doesn't run resource code generation, so the generated class wouldn't exist there and every x:Static would fail.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$resx = Join-Path $root 'src\ProGuard.UI\Resources\Strings.resx'
$out = Join-Path $root 'src\ProGuard.UI\Resources\Strings.cs'

[xml]$doc = Get-Content -LiteralPath $resx -Raw -Encoding UTF8
$keys = @($doc.root.data | Where-Object { -not $_.type -and -not $_.mimetype } | ForEach-Object { $_.name })
$duplicates = $keys | Group-Object | Where-Object Count -gt 1
if ($duplicates) { throw "Duplicate keys in Strings.resx: $($duplicates.Name -join ', ')" }
foreach ($key in $keys) { if ($key -notmatch '^[A-Za-z_][A-Za-z0-9_]*$') { throw "Key '$key' isn't a valid C# identifier." } }

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// <auto-generated>')
[void]$sb.AppendLine('//   Generated by tools/i18n/Update-Strings.ps1 from Strings.resx. Don''t edit: change the .resx and run the script.')
[void]$sb.AppendLine('// </auto-generated>')
[void]$sb.AppendLine('#nullable enable')
[void]$sb.AppendLine('using System.Globalization;')
[void]$sb.AppendLine('using System.Resources;')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('namespace ProGuard.UI.Resources;')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('/// <summary>The UI''s text in the current UI culture (English when a language has no translation for a key).</summary>')
[void]$sb.AppendLine('public static class Strings')
[void]$sb.AppendLine('{')
[void]$sb.AppendLine('    public static ResourceManager ResourceManager { get; } = new("ProGuard.UI.Resources.Strings", typeof(Strings).Assembly);')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('    /// <summary>Null means the current UI culture.</summary>')
[void]$sb.AppendLine('    public static CultureInfo? Culture { get; set; }')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('    private static string Get(string key) => ResourceManager.GetString(key, Culture) ?? key;')
foreach ($key in ($keys | Sort-Object)) {
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine("    public static string $key => Get(nameof($key));")
}
[void]$sb.AppendLine('}')
[IO.File]::WriteAllText($out, $sb.ToString().Replace("`r`n", "`n").Replace("`n", "`r`n"), (New-Object Text.UTF8Encoding($true)))
"Wrote $out ($($keys.Count) strings)"
